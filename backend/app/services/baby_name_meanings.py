def apply_meaning_fixes(entries):
    """Swaps in the corrected Tamil meaning where one exists.

    `entries` is the (name_en, name_ta, meaning_en, meaning_ta, gender,
    religion) tuple list used by the banks.
    """
    fixed = []
    for e in entries:
        better = MEANING_TA_FIXES.get(e[0])
        fixed.append((e[0], e[1], e[2], better, e[4], e[5]) if better else e)
    return fixed

