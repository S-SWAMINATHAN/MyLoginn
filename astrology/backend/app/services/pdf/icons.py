def icon_for(label: str) -> str:
    text = str(label or "")
    for rx, name in _COMPILED:
        if rx.search(text):
            return name
    return "star"


@lru_cache(maxsize=None)
def _uri(name: str) -> str:
    body = SVG.get(name, SVG["star"])
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
           f'stroke="{ICON_BLUE}" stroke-width="2.1" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("utf-8")).decode("ascii")


def icon(label: str = "", name: str = "", cls: str = "ic") -> str:
    """<img> of the icon for `label` (or the named icon). Sized in em by the
    `.ic` CSS rule so it always matches the text beside it."""
    return f'<img class="{cls}" src="{_uri(name or icon_for(label))}" alt=""/>'


