const TABLE: Record<string, string> = Object.fromEntries(Object.entries(RAW).map(([k, v]) => [placeKey(k), v]));

/** Standard Tamil name of a town / city typed in English, or undefined when not listed. */
export function curatedPlaceTa(englishTown: string): string | undefined {
  const k = placeKey(englishTown);
  if (!k) return undefined;
  if (TABLE[k]) return TABLE[k];
  // "Palakkad District", "Coimbatore North", "Erode Taluk" → the town itself
  const head = placeKey(String(englishTown).replace(/\b(district|taluk|taluka|city|town|north|south|east|west|corporation|municipality)\b/gi, ""));
  return head && head !== k ? TABLE[head] : undefined;
}
