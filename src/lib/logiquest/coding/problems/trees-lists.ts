  const keys = r.shuffle(Array.from({ length: 40 }, (_, i) => i + 1)).slice(0, r.int(4, 14));
  const L = new Map<number, number>(), R = new Map<number, number>();
  for (const x of keys.slice(1)) { let u = keys[0]; for (;;) { const m = x < u ? L : R; const nx = m.get(u); if (nx === undefined) { m.set(u, x); break; } u = nx; } }
